def render_report_pdf(document: dict) -> bytes:
    """Render the stored analysis document as a multi-page PDF report."""
    pdf = PdfBuilder(title="SafeFlux engineering report")
    goal = document.get("goal") or "(no goal recorded)"
    pdf.heading("SafeFlux engineering report", size=18)
    pdf.text(goal, size=11, bold=True)
    pdf.rule()

    interpreted = document.get("interpreted_change") or {}
    pdf.heading("Interpreted change")
    pdf.key_value("Direction", str(interpreted.get("direction") or "not stated"))
    pdf.key_value("Magnitude", str(interpreted.get("magnitude") or "not stated"))
    pdf.key_value(
        "Variables",
        ", ".join(interpreted.get("variables") or []) or "default search set",
    )

    original = document.get("original") or {}
    counts = original.get("counts") or {}
    pdf.heading("Overview")
    pdf.key_value("Status", str(document.get("status") or original.get("status") or ""))
    pdf.key_value("Scenarios evaluated", str(counts.get("scenarios", 0)))
    pdf.key_value("Failing", str(counts.get("failing", 0)))
    pdf.key_value("Violations", str(counts.get("violation", 0)))
    pdf.key_value("Safeguard activations", str(counts.get("safeguard_activated", 0)))

    pdf.heading("Scenarios")
    for case in (original.get("cases") or [])[:40]:
        peaks = case.get("peaks") or {}
        pdf.bullet(
            f"{case.get('label') or case.get('key')}: status={case.get('status')}, "
            f"peak T={peaks.get('temperature_c')}, peak P={peaks.get('pressure_bar')}, "
            f"peak level={peaks.get('level_pct')}"
        )
    if len(original.get("cases") or []) > 40:
        pdf.text("(remaining scenarios omitted from the PDF; the app shows all)", size=9)

    pdf.heading("Failures")
    failures = document.get("failures") or []
    if not failures:
        pdf.text(NO_UNSAFE_DETECTED_SENTENCE)
    for failure in failures[:20]:
        peaks = failure.get("peaks") or {}
        pdf.text(failure.get("label") or str(failure.get("key")), bold=True)
        pdf.key_value("Status", str(failure.get("status")), indent=14)
        pdf.key_value(
            "Peaks",
            f"T={peaks.get('temperature_c')} P={peaks.get('pressure_bar')} L={peaks.get('level_pct')}",
            indent=14,
        )

    pdf.heading("Counterfactuals")
    for row in document.get("counterfactuals") or []:
        pdf.text(f"{row.get('label')} ({row.get('variable')} -> {row.get('value')})", bold=True)
        pdf.key_value("Resulting status", str(row.get("status")), indent=14)
        pdf.key_value("Improved", str(row.get("improved")), indent=14)

    pdf.heading("Safeguards")
    safeguards = (document.get("safeguards") or {}).get("timings") or []
    pdf.text(SAFEGUARD_NOTE_SENTENCE, size=9)
    for timing in safeguards:
        pdf.bullet(
            f"{timing.get('safeguard')}: trigger={timing.get('trigger_time_s')}s, "
            f"response={timing.get('response_time_s')}s, "
            f"violation={timing.get('violation_time_s')}s, prevented={timing.get('prevented')}"
        )

    pdf.heading("Evidence")
    pdf.text(EVIDENCE_SENTENCE, size=9)
    pdf.text(ANALYSIS_DISCLAIMER_SENTENCE, size=9)

    ai = document.get("ai_explanation") or {}
    if isinstance(ai, dict) and ai.get("text"):
        pdf.heading("AI explanation")
        pdf.text(str(ai.get("text")), size=9)
        pdf.text(AI_SEPARATION_SENTENCE, size=9)

    return pdf.build()


NO_UNSAFE_DETECTED_SENTENCE = (
    "No unsafe condition was detected within the tested simulation scenarios."
)
SAFEGUARD_NOTE_SENTENCE = (
    "Times describe the simulated response of the modelled safeguard, not the "
    "behaviour of a real plant."
)
EVIDENCE_SENTENCE = (
    "Every value in this report comes from the deterministic simulator and the "
    "configured safety limits; nothing is estimated."
)
ANALYSIS_DISCLAIMER_SENTENCE = (
    "SafeFlux explores simulated scenarios only; it never actuates real equipment "
    "and never guarantees a real plant is safe."
)
AI_SEPARATION_SENTENCE = (
    "The section above is an AI-generated explanation of the evidence. It is not "
    "simulation evidence and carries no verdict."
)


__all__ = ["PdfBuilder", "render_report_pdf"]
